/*
  Generates src/data/videoMeta.ts from the real media files and git history.

  VideoObject structured data requires name, description, thumbnailUrl and
  uploadDate. uploadDate must be a real date, so it comes from the commit that
  first added each file rather than being invented. Duration and dimensions are
  probed from the files themselves.

  Baked to a committed file because ffprobe is not available during a Vercel
  build. Re-run with `npm run video:meta` after adding or replacing a clip.
*/
import { execFileSync } from 'node:child_process'
import { readdirSync, writeFileSync } from 'node:fs'

const probe = (f, entries) =>
  execFileSync('ffprobe', [
    '-v', 'error', '-select_streams', 'v:0',
    '-show_entries', entries, '-of', 'csv=p=0', f,
  ]).toString().trim()

/* ISO 8601 duration, e.g. 12.1s -> PT12S */
const iso = (secs) => {
  const s = Math.round(secs)
  const m = Math.floor(s / 60)
  return m ? `PT${m}M${s % 60}S` : `PT${s}S`
}

const rows = []
for (const name of readdirSync('public/work').filter((f) => f.endsWith('.mp4')).sort()) {
  const file = `public/work/${name}`
  const [w, h] = probe(file, 'stream=width,height').split(',')
  const dur = parseFloat(probe(file, 'stream=duration'))

  /* first commit that introduced this file = the date it was published */
  const added = execFileSync('git', [
    'log', '--diff-filter=A', '--format=%aI', '-1', '--', file,
  ]).toString().trim()

  rows.push({
    media: `/work/${name}`,
    uploadDate: added ? added.slice(0, 10) : new Date().toISOString().slice(0, 10),
    duration: iso(dur),
    seconds: Math.round(dur),
    width: +w,
    height: +h,
  })
}

const body = `/*
  GENERATED by scripts/gen-video-meta.mjs — do not edit by hand.
  Run \`npm run video:meta\` to refresh after changing any clip.

  uploadDate is the date the file was first committed, so VideoObject carries a
  real publication date rather than an invented one.
*/
export type VideoMeta = {
  uploadDate: string
  duration: string
  seconds: number
  width: number
  height: number
}

export const videoMeta: Record<string, VideoMeta> = {
${rows
  .map(
    (r) =>
      `  '${r.media}': { uploadDate: '${r.uploadDate}', duration: '${r.duration}', seconds: ${r.seconds}, width: ${r.width}, height: ${r.height} },`,
  )
  .join('\n')}
}
`

writeFileSync('src/data/videoMeta.ts', body)
console.log(`wrote src/data/videoMeta.ts — ${rows.length} clips`)
rows.forEach((r) =>
  console.log(`  ${r.media.padEnd(30)} ${r.uploadDate}  ${r.duration.padEnd(7)} ${r.width}x${r.height}`),
)
